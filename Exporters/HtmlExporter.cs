        private static void AppendGpuSection(StringBuilder sb, HardwareReport r)
        {
            Title(sb, "gpu", "GPU");

            int n = MaxCount(r.GpuNames, r.GpuMemories, r.GpuDrivers, r.GpuManufacturers);
            for (int i = 0; i < n; i++)
