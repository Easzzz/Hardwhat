                Pair(sb, "Name", At(r.GpuNames, i));
                Pair(sb, "Memory", At(r.GpuMemories, i));
                Pair(sb, "Driver", At(r.GpuDrivers, i));
                Pair(sb, "Manufacturer", At(r.GpuManufacturers, i));
                EndCard(sb);
            }
        }

